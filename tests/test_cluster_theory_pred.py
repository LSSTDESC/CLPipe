"""Tests for clpipe.cluster_theory_pred.

The files are generated by CLPFirecrown, as in a pipeline run, and the
prediction is compared with the theory vector CosmoSIS computes from the
same files with the test sampler.
"""
import numpy as np
import pytest

# The module imports firecrown at import time, so skip the whole file when
# the science stack is not installed (fast CI job).
pytest.importorskip("firecrown")

from clpipe.cluster_theory_pred import compute_cluster_predictions
from .test_clp_firecrown import (
    FIRECROWN_PARAMETERS,
    _base_firecrown_config,
    _make_stage,
    _run_full_cosmosis,
)


def _generate_files(tmp_path, sacc_fixture, fiducial_cosmology_path, cfg):
    """Write the CLPFirecrown outputs to tmp_path and return the sampler file path."""
    sacc_in_place = tmp_path / "clusters_sacc_file_cov.sacc"
    sacc_in_place.write_bytes(sacc_fixture.read_bytes())
    _make_stage(tmp_path, sacc_in_place, fiducial_cosmology_path, cfg).run()
    return tmp_path / "sampler_file.ini"


@pytest.mark.slow
@pytest.mark.parametrize(
    "overrides",
    [
        {},
        {"use_shear_profile": False, "use_mean_deltasigma": False},
        {"use_grid": False, "use_shear_profile": False, "use_mean_deltasigma": False},
    ],
    ids=["counts_deltasigma", "counts_only", "exact_recipe"],
)
def test_prediction_matches_cosmosis(
    full_stack, tmp_path, mock_fiducial_cosmology, mock_cluster_sacc_dense, overrides
):
    cfg = _base_firecrown_config(sampler="test", filename=str(tmp_path / "chain.txt"), **overrides)
    result = _run_full_cosmosis(tmp_path, mock_fiducial_cosmology, cfg, mock_cluster_sacc_dense)
    assert result.returncode == 0, f"stdout:\n{result.stdout}\n\nstderr:\n{result.stderr}"
    expected = np.loadtxt(tmp_path / "output_counts_mean_mass" / "data_vector" / "firecrown_theory.txt")

    pred = compute_cluster_predictions(tmp_path / "sampler_file.ini")
    theory = [pred.counts.theory]
    if pred.shear is not None:
        theory.append(pred.shear.theory)
    # CosmoSIS takes the power spectrum from its CAMB module, here CCL
    # computes it, hence the tolerance.
    np.testing.assert_allclose(np.concatenate(theory), expected, rtol=5e-3)
    assert (pred.shear is None) == (not cfg["use_shear_profile"])


@pytest.mark.slow
def test_params_override_values_file(full_stack, tmp_path, mock_fiducial_cosmology, mock_cluster_sacc_dense):
    cfg = _base_firecrown_config(use_shear_profile=False, use_mean_deltasigma=False)
    sampler_file = _generate_files(tmp_path, mock_cluster_sacc_dense, mock_fiducial_cosmology, cfg)

    start = compute_cluster_predictions(sampler_file)
    assert start.parameters["cosmological_parameters--sigma_8"] == 0.8
    assert start.parameters["firecrown_number_counts--mass_distribution_mu0"] == pytest.approx(
        FIRECROWN_PARAMETERS["mass_distribution_mu0"]["values"][1]
    )

    pred = compute_cluster_predictions(
        sampler_file,
        params={"cosmological_parameters--sigma_8": 0.85, "mass_distribution_mu0": 3.5},
    )
    assert pred.parameters["cosmological_parameters--sigma_8"] == 0.85
    assert pred.parameters["firecrown_number_counts--mass_distribution_mu0"] == 3.5
    assert not np.allclose(pred.counts.theory, start.counts.theory)


def test_unknown_parameter_raises(full_stack, tmp_path, mock_fiducial_cosmology, mock_cluster_sacc_dense):
    sampler_file = _generate_files(
        tmp_path, mock_cluster_sacc_dense, mock_fiducial_cosmology, _base_firecrown_config()
    )
    with pytest.raises(ValueError, match="'not_a_parameter' is not in the values file"):
        compute_cluster_predictions(sampler_file, params={"not_a_parameter": 1.0})
    with pytest.raises(ValueError, match="'firecrown_number_counts--omega_c' is not in the values file"):
        compute_cluster_predictions(sampler_file, params={"firecrown_number_counts--omega_c": 0.3})
